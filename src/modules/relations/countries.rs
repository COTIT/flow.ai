/// Country by ISO code, any case. None = rinvex has no such file (Laravel threw).
pub fn find(code: &str) -> Option<&'static Country> {
    let code = code.trim().to_ascii_uppercase();
    ALL.binary_search_by(|c| c.code.cmp(code.as_str()))
        .ok()
        .map(|i| &ALL[i])
}
